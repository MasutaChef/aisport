def intensite_vers_couleur(pourcentage):
    if pourcentage <= 5:
        return "none" # Transparent si inactif
    r_base, g_base, b_base = 255, 255, 255
    r = 255 
    g = int(g_base - (g_base * pourcentage / 100))
    b = int(b_base - (b_base * pourcentage / 100))
    return f"#{r:02x}{g:02x}{b:02x}"

